//array methods...>1. pop()---> To remove the end of element
let bike=["Tvs", "KTM", "Suzuki"]
bike.pop()
console.log(bike)

//push()-->add element at the end.
bike.push("Pulsar")
console.log(bike)
console.log(bike.push("Pulsar"))

//shift()-->remove the first element
bike.shift()
console.log(bike)

//unshift()-->add the element at the beginning
bike.unshift("TVS Raider 125")
console.log(bike[1])

